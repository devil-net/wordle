/**
 * Get a random word of the specified length
 */
export function getRandomWord(length: number = 5): string {
  let wordList: string[];
  switch (length) {
    case 4: wordList = FOUR_LETTER_WORDS; break;
    case 6: wordList = SIX_LETTER_WORDS; break;
    default: wordList = ANSWER_WORDS; break;
  }
  return wordList[Math.floor(Math.random() * wordList.length)];
}

/**
 * Check if a word is valid for guessing
 * Strictly requires meaningful English words from our dictionary!
 */
export function isValidWord(word: string, length: number = 5): boolean {
  if (!word || word.length !== length) return false;
  const lower = word.toLowerCase();
  
  return (
    ANSWER_WORDS.includes(lower) ||
    VALID_GUESSES.includes(lower) ||
    FOUR_LETTER_WORDS.includes(lower) ||
    SIX_LETTER_WORDS.includes(lower)
  );
}

/**
 * Get the daily word using the date as a deterministic seed
 */
export function getDailyWord(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = now.getMonth();
  const day = now.getDate();
  
  const dayIndex = (year * 366 + month * 31 + day) % ANSWER_WORDS.length;
  return ANSWER_WORDS[dayIndex];
}
